printf 'two lanes on one repo cannot corrupt the shared hooks\n'
# The other half of the shared-directory problem. pre-commit truncates the hook
# file before it writes it, so an unguarded second install can read the first one
# half written, judge it a stranger's hook and move the wreckage over the .legacy
# backup. Run two lanes at once against a deliberately slow install and assert
# that exactly one of them wrote, and that what landed is a whole hook.
RACEREPO="$TEST_DIR/racerepo"
new_repo "$RACEREPO"
printf 'repos: []\n' > "$RACEREPO/.pre-commit-config.yaml"
git -C "$RACEREPO" add .pre-commit-config.yaml
git -C "$RACEREPO" commit -qm hooks
: > "$STUB_PC_CALLS"
STUB_PC_SLOW=1 lane up racea --repo "$RACEREPO" --slot 7 >"$TEST_DIR/racea.out" 2>&1 &
RACE_A=$!
STUB_PC_SLOW=1 lane up raceb --repo "$RACEREPO" --slot 8 >"$TEST_DIR/raceb.out" 2>&1 &
RACE_B=$!
EXIT=0; wait "$RACE_A" || EXIT=$?
check "the first lane survived the race" "$EXIT" "0"
EXIT=0; wait "$RACE_B" || EXIT=$?
check "the second lane survived the race" "$EXIT" "0"
check "only one of the two ran the install" "$(pc_calls)" "1"
check "the hook that landed is whole" \
  "$(grep -c 'File generated by pre-commit' "$RACEREPO/.git/hooks/pre-commit")" "1"
check "no backup was clobbered into existence" \
  "$([ -e "$RACEREPO/.git/hooks/pre-commit.legacy" ] && echo y || echo n)" "n"
RACE_OUT=$(cat "$TEST_DIR/racea.out" "$TEST_DIR/raceb.out")
has "one lane installed" "$RACE_OUT" "Commit hooks (pre-commit): installed"
has "and the other found them present" "$RACE_OUT" "Commit hooks (pre-commit): present"
check "the lock is released afterwards" \
  "$([ -e "$RACEREPO/.git/.session-lane-hooks.lock" ] && echo y || echo n)" "n"
lane down racea >/dev/null 2>&1
lane down raceb >/dev/null 2>&1

